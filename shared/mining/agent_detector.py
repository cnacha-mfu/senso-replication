"""
Agent Adoption Detector for SENSO Framework

Detects AI coding agent usage in GitHub repositories using multiple signals:
- File-based: CLAUDE.md, AGENTS.md, .cursorrules, copilot configs
- Author-based: Co-Authored-By tags with known agent patterns
- Branch-based: Agent-specific branch naming conventions
- Message-based: Agent signatures in commit messages

Used by: Paper 1 (manifest collection), Paper 2 (agent features),
         Paper 3 (treatment group identification), Paper 4 (anti-pattern detection)

Usage:
    python shared/mining/agent_detector.py --token $GITHUB_TOKEN --output data/raw/agent_detection/
    python shared/mining/agent_detector.py --token $GITHUB_TOKEN --repo owner/name  # single repo
"""

import argparse
import json
import logging
import re
import time
from dataclasses import dataclass, field, asdict
from datetime import datetime
from pathlib import Path
from typing import Optional

import requests

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)


# ── Agent Signal Definitions ──────────────────────────────────────────────────

AGENT_FILES = {
    "claude_code": ["CLAUDE.md", ".claude/settings.json", ".claude/commands"],
    "codex": ["AGENTS.md", ".agents/config.json"],
    "cursor": [".cursorrules", ".cursor/settings.json"],
    "copilot": [".github/copilot-instructions.md", ".github/copilot-settings.json"],
    "cline": [".clinerules", ".cline/settings.json"],
    "aider": [".aider.conf.yml", ".aiderignore"],
    "windsurf": [".windsurfrules"],
}

COAUTHOR_PATTERNS = {
    "claude_code": [
        r"co-authored-by:.*claude.*@anthropic",
        r"co-authored-by:.*claude.*noreply",
    ],
    "copilot": [
        r"co-authored-by:.*copilot.*@github",
        r"co-authored-by:.*github-copilot",
    ],
    "codex": [
        r"co-authored-by:.*codex.*@openai",
    ],
}

BRANCH_PATTERNS = {
    "codex": [r"^codex/", r"^codex-"],
    "devin": [r"^devin/", r"^devin-"],
    "claude": [r"^claude/", r"^claude-"],
    "copilot": [r"^copilot/", r"^copilot-fix-"],
}

MESSAGE_PATTERNS = {
    "generic_agent": [
        r"generated by ai",
        r"ai-generated",
        r"auto-generated by",
        r"🤖.*generated",
    ],
    "claude_code": [r"generated by claude"],
    "codex": [r"generated by codex", r"codex agent"],
}


@dataclass
class AgentSignal:
    """A single detected agent signal."""
    signal_type: str       # file, coauthor, branch, message
    agent_type: str        # claude_code, codex, cursor, copilot, generic_agent
    evidence: str          # the specific file/pattern/message found
    timestamp: Optional[str] = None  # when this signal first appeared


@dataclass
class RepoAgentProfile:
    """Complete agent adoption profile for a repository."""
    full_name: str
    signals: list = field(default_factory=list)
    has_agent: bool = False
    dominant_agent: Optional[str] = None
    adoption_date: Optional[str] = None  # earliest signal timestamp
    agent_file_count: int = 0
    agent_commit_count: int = 0
    total_signal_count: int = 0
    scan_timestamp: str = ""

    def finalize(self):
        self.total_signal_count = len(self.signals)
        self.has_agent = self.total_signal_count > 0
        if self.signals:
            # Dominant agent = most frequent agent type
            agent_counts = {}
            for s in self.signals:
                agent_counts[s.agent_type] = agent_counts.get(s.agent_type, 0) + 1
            self.dominant_agent = max(agent_counts, key=agent_counts.get)
            # Adoption date = earliest signal
            dates = [s.timestamp for s in self.signals if s.timestamp]
            if dates:
                self.adoption_date = min(dates)
        self.scan_timestamp = datetime.now().isoformat()


class GitHubClient:
    """GitHub API client with rate limiting and caching."""

    BASE = "https://api.github.com"

    def __init__(self, token: str):
        self.session = requests.Session()
        self.session.headers.update({
            "Authorization": f"token {token}",
            "Accept": "application/vnd.github.v3+json",
        })
        self.calls = 0

    def get(self, endpoint: str, params: dict = None) -> Optional[dict | list]:
        url = f"{self.BASE}/{endpoint}" if not endpoint.startswith("http") else endpoint
        self.calls += 1
        try:
            r = self.session.get(url, params=params, timeout=30)
            remaining = int(r.headers.get("X-RateLimit-Remaining", 999))
            if remaining < 20:
                reset = int(r.headers.get("X-RateLimit-Reset", 0))
                wait = max(reset - time.time(), 0) + 2
                logger.warning(f"Rate limit low ({remaining}). Sleeping {wait:.0f}s")
                time.sleep(wait)
            if r.status_code == 200:
                return r.json()
            elif r.status_code == 403:
                time.sleep(60)
                return self.get(endpoint, params)
            else:
                return None
        except requests.RequestException as e:
            logger.warning(f"Request failed: {e}")
            return None

    def search_code(self, query: str, per_page: int = 100) -> list:
        """Search code on GitHub. Returns list of results."""
        results = []
        page = 1
        while True:
            data = self.get("search/code", {
                "q": query, "per_page": per_page, "page": page
            })
            if not data or "items" not in data:
                break
            results.extend(data["items"])
            if len(data["items"]) < per_page:
                break
            page += 1
            time.sleep(2)  # Search API rate limit is stricter
        return results


def detect_file_signals(client: GitHubClient, full_name: str) -> list[AgentSignal]:
    """Detect agent config files in a repository."""
    signals = []
    for agent_type, filenames in AGENT_FILES.items():
        for filename in filenames:
            # Check if file exists via contents API
            data = client.get(f"repos/{full_name}/contents/{filename}")
            if data and isinstance(data, dict) and "name" in data:
                # Get file creation date from first commit
                commits = client.get(
                    f"repos/{full_name}/commits",
                    {"path": filename, "per_page": 1, "page": 1}
                )
                # Get the oldest commit for this file
                oldest = client.get(
                    f"repos/{full_name}/commits",
                    {"path": filename, "per_page": 1, "order": "asc"}
                )
                timestamp = None
                if oldest and isinstance(oldest, list) and len(oldest) > 0:
                    timestamp = oldest[0].get("commit", {}).get("author", {}).get("date")
                elif commits and isinstance(commits, list) and len(commits) > 0:
                    timestamp = commits[0].get("commit", {}).get("author", {}).get("date")

                signals.append(AgentSignal(
                    signal_type="file",
                    agent_type=agent_type,
                    evidence=filename,
                    timestamp=timestamp,
                ))
    return signals


def detect_coauthor_signals(client: GitHubClient, full_name: str,
                            sample_size: int = 200) -> list[AgentSignal]:
    """Detect Co-Authored-By agent tags in recent commits."""
    signals = []
    data = client.get(f"repos/{full_name}/commits", {"per_page": sample_size})
    if not data:
        return signals

    for commit in data:
        msg = (commit.get("commit", {}).get("message") or "").lower()
        for agent_type, patterns in COAUTHOR_PATTERNS.items():
            for pattern in patterns:
                if re.search(pattern, msg):
                    timestamp = commit.get("commit", {}).get("author", {}).get("date")
                    signals.append(AgentSignal(
                        signal_type="coauthor",
                        agent_type=agent_type,
                        evidence=f"Pattern: {pattern}",
                        timestamp=timestamp,
                    ))
                    break  # One match per agent per commit is enough
    return signals


def detect_branch_signals(client: GitHubClient, full_name: str) -> list[AgentSignal]:
    """Detect agent-specific branch naming patterns."""
    signals = []
    branches = client.get(f"repos/{full_name}/branches", {"per_page": 100})
    if not branches:
        return signals

    for branch in branches:
        name = branch.get("name", "").lower()
        for agent_type, patterns in BRANCH_PATTERNS.items():
            for pattern in patterns:
                if re.search(pattern, name):
                    signals.append(AgentSignal(
                        signal_type="branch",
                        agent_type=agent_type,
                        evidence=f"Branch: {branch['name']}",
                    ))
                    break
    return signals


def detect_message_signals(client: GitHubClient, full_name: str,
                           sample_size: int = 200) -> list[AgentSignal]:
    """Detect agent signatures in commit messages."""
    signals = []
    data = client.get(f"repos/{full_name}/commits", {"per_page": sample_size})
    if not data:
        return signals

    for commit in data:
        msg = (commit.get("commit", {}).get("message") or "").lower()
        for agent_type, patterns in MESSAGE_PATTERNS.items():
            for pattern in patterns:
                if re.search(pattern, msg):
                    timestamp = commit.get("commit", {}).get("author", {}).get("date")
                    signals.append(AgentSignal(
                        signal_type="message",
                        agent_type=agent_type,
                        evidence=f"Pattern: {pattern}",
                        timestamp=timestamp,
                    ))
                    break
    return signals


def scan_repository(client: GitHubClient, full_name: str) -> RepoAgentProfile:
    """Run all detection methods on a single repository."""
    logger.info(f"Scanning {full_name}...")
    profile = RepoAgentProfile(full_name=full_name)

    profile.signals.extend(detect_file_signals(client, full_name))
    profile.signals.extend(detect_coauthor_signals(client, full_name))
    profile.signals.extend(detect_branch_signals(client, full_name))
    profile.signals.extend(detect_message_signals(client, full_name))

    profile.finalize()

    status = f"AGENT ({profile.dominant_agent}, {profile.total_signal_count} signals)" \
        if profile.has_agent else "NO AGENT"
    logger.info(f"  {full_name}: {status}")
    return profile


def search_agent_repos(client: GitHubClient) -> list[str]:
    """Search GitHub for repositories with known agent config files."""
    repos = set()

    search_queries = [
        "filename:CLAUDE.md",
        "filename:AGENTS.md",
        "filename:.cursorrules",
        "filename:.clinerules",
        "filename:.windsurfrules",
    ]

    for query in search_queries:
        logger.info(f"Searching: {query}")
        results = client.search_code(query)
        for item in results:
            repo_name = item.get("repository", {}).get("full_name")
            if repo_name:
                repos.add(repo_name)
        logger.info(f"  Found {len(results)} results, {len(repos)} unique repos total")
        time.sleep(5)

    return sorted(repos)


def main():
    parser = argparse.ArgumentParser(description="SENSO Agent Detector")
    parser.add_argument("--token", required=True, help="GitHub personal access token")
    parser.add_argument("--output", default="data/raw/agent_detection/",
                        help="Output directory")
    parser.add_argument("--repo", help="Scan a single repository (owner/name)")
    parser.add_argument("--search", action="store_true",
                        help="Search GitHub for agent-using repos")
    parser.add_argument("--repos-file", help="JSON file with list of repos to scan")
    args = parser.parse_args()

    client = GitHubClient(args.token)
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)

    if args.repo:
        # Single repo scan
        profile = scan_repository(client, args.repo)
        out_file = output / f"{args.repo.replace('/', '__')}.json"
        with open(out_file, "w") as f:
            json.dump(asdict(profile), f, indent=2, default=str)
        print(json.dumps(asdict(profile), indent=2, default=str))

    elif args.search:
        # Search and scan
        logger.info("Phase 1: Searching GitHub for agent-using repos...")
        repo_names = search_agent_repos(client)
        logger.info(f"Found {len(repo_names)} candidate repos")

        # Save candidate list
        with open(output / "candidates.json", "w") as f:
            json.dump(repo_names, f, indent=2)

        # Scan each candidate
        logger.info("Phase 2: Scanning candidates...")
        profiles = []
        for i, name in enumerate(repo_names):
            logger.info(f"[{i+1}/{len(repo_names)}] {name}")
            try:
                profile = scan_repository(client, name)
                profiles.append(asdict(profile))
                time.sleep(1)
            except Exception as e:
                logger.error(f"  Error: {e}")

        # Save all profiles
        with open(output / "agent_profiles.json", "w") as f:
            json.dump(profiles, f, indent=2, default=str)

        # Summary
        agent_repos = [p for p in profiles if p["has_agent"]]
        logger.info(f"\nSummary: {len(agent_repos)}/{len(profiles)} repos have agent signals")
        logger.info(f"API calls: {client.calls}")

    elif args.repos_file:
        # Scan from list
        with open(args.repos_file) as f:
            repo_names = json.load(f)
        if isinstance(repo_names[0], dict):
            repo_names = [r["full_name"] for r in repo_names]

        profiles = []
        for i, name in enumerate(repo_names):
            logger.info(f"[{i+1}/{len(repo_names)}] {name}")
            try:
                profile = scan_repository(client, name)
                profiles.append(asdict(profile))
                time.sleep(0.5)
            except Exception as e:
                logger.error(f"  Error: {e}")

        with open(output / "agent_profiles.json", "w") as f:
            json.dump(profiles, f, indent=2, default=str)

    else:
        parser.error("Provide --repo, --search, or --repos-file")


if __name__ == "__main__":
    main()
