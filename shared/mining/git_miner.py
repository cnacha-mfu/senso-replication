"""
Git Repository Miner for SENSO Framework

Extracts monthly evolution metrics from Git repositories using PyDriller.
Produces per-repository, per-month metric panels used by all papers.

Used by: Paper 1 (ontology population), Paper 2 (node features),
         Paper 3 (Lehman's law metrics), Paper 4 (guardrail evaluation)

Usage:
    python shared/mining/git_miner.py --repo https://github.com/owner/name --output data/raw/repos/
    python shared/mining/git_miner.py --repos-file data/raw/agent_detection/selected.json --output data/raw/repos/
"""

import argparse
import json
import logging
from collections import defaultdict
from datetime import datetime
from pathlib import Path

from pydriller import Repository

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)

BUG_FIX_KEYWORDS = [
    "fix", "bug", "defect", "patch", "repair", "resolve",
    "issue", "error", "fault", "failure", "crash", "exception",
    "hotfix", "hot-fix", "bugfix", "bug-fix", "regression",
    "correct", "workaround",
]


def is_bug_fix(message: str) -> bool:
    msg = message.lower()
    return any(kw in msg for kw in BUG_FIX_KEYWORDS)


def is_agent_commit(commit) -> bool:
    """Detect if a commit was made by or with a coding agent."""
    msg = (commit.msg or "").lower()
    author = (commit.author.name or "").lower()

    agent_indicators = [
        "co-authored-by" in msg and any(
            a in msg for a in ["claude", "copilot", "codex", "cursor"]
        ),
        "generated by" in msg,
        "ai-generated" in msg,
        any(bot in author for bot in ["[bot]", "codex", "devin"]),
    ]
    return any(agent_indicators)


def mine_monthly_metrics(repo_path: str, output_dir: Path):
    """Extract monthly metrics from a repository."""
    output_dir.mkdir(parents=True, exist_ok=True)

    monthly = defaultdict(lambda: {
        "commit_count": 0,
        "merge_count": 0,
        "authors": set(),
        "lines_added": 0,
        "lines_deleted": 0,
        "files_changed": 0,
        "bug_fix_count": 0,
        "agent_commit_count": 0,
        "agent_lines_added": 0,
        "commit_sizes": [],       # lines changed per commit
        "files_per_commit": [],   # files changed per commit
        "file_complexities": {},  # file -> latest complexity
        "file_nlocs": {},         # file -> latest nloc
    })

    commit_count = 0
    logger.info(f"Mining {repo_path}...")

    try:
        for commit in Repository(repo_path).traverse_commits():
            month = commit.author_date.strftime("%Y-%m")
            m = monthly[month]

            m["commit_count"] += 1
            if commit.merge:
                m["merge_count"] += 1
            m["authors"].add(commit.author.email)
            m["lines_added"] += commit.insertions
            m["lines_deleted"] += commit.deletions
            m["files_changed"] += commit.files

            if is_bug_fix(commit.msg):
                m["bug_fix_count"] += 1

            agent = is_agent_commit(commit)
            if agent:
                m["agent_commit_count"] += 1
                m["agent_lines_added"] += commit.insertions

            commit_size = commit.insertions + commit.deletions
            m["commit_sizes"].append(commit_size)
            m["files_per_commit"].append(commit.files)

            # Per-file metrics from modifications
            for mod in commit.modified_files:
                if mod.new_path and mod.complexity is not None:
                    m["file_complexities"][mod.new_path] = mod.complexity
                if mod.new_path and mod.nloc is not None:
                    m["file_nlocs"][mod.new_path] = mod.nloc

            commit_count += 1
            if commit_count % 1000 == 0:
                logger.info(f"  Processed {commit_count} commits...")

    except Exception as e:
        logger.error(f"Error mining {repo_path}: {e}")

    # Convert to serializable format and compute aggregates
    results = []
    for month in sorted(monthly.keys()):
        m = monthly[month]
        sizes = m["commit_sizes"] or [0]
        files = m["files_per_commit"] or [0]
        complexities = list(m["file_complexities"].values()) or [0]
        nlocs = list(m["file_nlocs"].values()) or [0]

        results.append({
            "month": month,
            "commit_count": m["commit_count"],
            "merge_count": m["merge_count"],
            "unique_authors": len(m["authors"]),
            "lines_added": m["lines_added"],
            "lines_deleted": m["lines_deleted"],
            "total_churn": m["lines_added"] + m["lines_deleted"],
            "files_changed": m["files_changed"],
            "bug_fix_count": m["bug_fix_count"],
            "bug_fix_ratio": m["bug_fix_count"] / max(m["commit_count"], 1),
            "merge_ratio": m["merge_count"] / max(m["commit_count"], 1),
            "agent_commit_count": m["agent_commit_count"],
            "agent_commit_ratio": m["agent_commit_count"] / max(m["commit_count"], 1),
            "agent_lines_ratio": m["agent_lines_added"] / max(m["lines_added"], 1),
            # Per-commit statistics
            "mean_commit_size": sum(sizes) / len(sizes),
            "median_commit_size": sorted(sizes)[len(sizes) // 2],
            "mean_files_per_commit": sum(files) / len(files),
            # Complexity snapshot
            "complexity_mean": sum(complexities) / len(complexities),
            "complexity_max": max(complexities),
            "complexity_file_count": len(m["file_complexities"]),
            # Size snapshot
            "nloc_total": sum(nlocs),
            "nloc_file_count": len(m["file_nlocs"]),
        })

    # Save
    out_file = output_dir / "monthly_metrics.json"
    with open(out_file, "w") as f:
        json.dump({
            "repo": repo_path,
            "total_commits": commit_count,
            "total_months": len(results),
            "mined_at": datetime.now().isoformat(),
            "monthly": results,
        }, f, indent=2)

    logger.info(f"  Done: {commit_count} commits, {len(results)} months → {out_file}")
    return results


def main():
    parser = argparse.ArgumentParser(description="SENSO Git Miner")
    parser.add_argument("--repo", help="Single repo URL or local path")
    parser.add_argument("--repos-file", help="JSON file with repo list")
    parser.add_argument("--output", required=True, help="Output base directory")
    args = parser.parse_args()

    output = Path(args.output)

    if args.repo:
        safe_name = args.repo.rstrip("/").split("/")[-2] + "__" + args.repo.rstrip("/").split("/")[-1]
        mine_monthly_metrics(args.repo, output / safe_name)

    elif args.repos_file:
        with open(args.repos_file) as f:
            repos = json.load(f)
        if isinstance(repos[0], dict):
            repos = [r.get("full_name") or r.get("repo") for r in repos]

        for i, repo in enumerate(repos):
            safe_name = repo.replace("/", "__")
            repo_dir = output / safe_name
            if (repo_dir / "monthly_metrics.json").exists():
                logger.info(f"[{i+1}/{len(repos)}] Skipping {repo} (exists)")
                continue
            logger.info(f"[{i+1}/{len(repos)}] Mining {repo}")
            try:
                mine_monthly_metrics(f"https://github.com/{repo}", repo_dir)
            except Exception as e:
                logger.error(f"  Failed: {e}")

    else:
        parser.error("Provide --repo or --repos-file")


if __name__ == "__main__":
    main()
